def main():
    parser = argparse.ArgumentParser(description="Train FraudGuard models")
    parser.add_argument("--generate", action="store_true",
                        help="Regenerate synthetic dataset before training")
    parser.add_argument("--rows", type=int, default=100_000,
                        help="Number of rows for dataset generation")
    parser.add_argument("--fraud-rate", type=float, default=0.04,
                        help="Target fraud rate for dataset generation")
    args = parser.parse_args()

    print("=" * 60)
    print("FRAUDGUARD — MODEL TRAINING PIPELINE")
    print("=" * 60)
    t_start = time.time()

    df = load_dataset(
        generate=args.generate,
        n_rows=args.rows,
        fraud_rate=args.fraud_rate,
    )
    X_train, X_test, y_train, y_test, scaler = preprocess(df)
    fraud_model = train_fraud_classifier(X_train, y_train)
    anomaly_model = train_anomaly_detector(X_train, y_train)
    metrics = evaluate(fraud_model, anomaly_model, X_test, y_test)
    latency_stats = run_latency_benchmark(fraud_model, anomaly_model, scaler)
    save_models(fraud_model, anomaly_model, scaler, metrics, latency_stats)

    elapsed = time.time() - t_start
    print(f"\nTotal training time: {elapsed:.1f}s")
    print("Done.\n")

    quick_integration_test()


if __name__ == "__main__":
    main()
